"""城市识别工具：把用户偏好的城市文本收敛为统一城市名，供各平台数据源映射成各自的参数。

不同平台的「城市」参数格式不同（BOSS 用 cityCode，猎聘用拼音/编码），
但「城市名」是通用的，因此这里只负责从简历/偏好文本里识别出一个标准城市名，
具体的编码映射交给各数据源自己维护。
"""
from __future__ import annotations

# 常用求职城市（按覆盖面排序，识别时优先命中更长的名称）
KNOWN_CITIES: List[str] = [
    "北京", "上海", "广州", "深圳", "杭州", "成都", "武汉", "南京", "西安",
    "苏州", "重庆", "长沙", "天津", "厦门", "东莞", "宁波", "佛山", "合肥",
    "青岛", "郑州", "无锡", "大连", "福州", "济南", "昆明", "哈尔滨", "沈阳",
    "石家庄", "南昌", "南宁", "常州", "珠海", "中山", "惠州", "嘉兴", "南通",
    "保定", "泉州", "贵阳", "太原", "烟台", "兰州", "海口",
]


def detect_city(text: str) -> str:
    """从任意文本（如偏好描述「前端+AI，深圳，20-30K」）中识别标准城市名。

    命中多个时返回第一个；未命中返回空串（由各数据源回退到「全国」）。
    """
    if not text:
        return ""
    for city in KNOWN_CITIES:
        if city in text:
            return city
    return ""
